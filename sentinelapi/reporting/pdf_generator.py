def generate_scan_pdfs(master_result: MasterScanResult, output_dir: Path) -> tuple[Path, Path]:
    """Generates both vulnerabilities.pdf and all_logs.pdf in the specified output directory.

    Returns:
        tuple[Path, Path]: (vulnerabilities_pdf_path, all_logs_pdf_path)
    """
    out_dir = Path(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    vuln_path = out_dir / "vulnerabilities.pdf"
    logs_path = out_dir / "all_logs.pdf"
    generate_vulnerabilities_pdf(master_result, vuln_path)
    generate_logs_pdf(master_result, logs_path)
    return vuln_path, logs_path
