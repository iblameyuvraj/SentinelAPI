def _esc(val: Any) -> str:
    """Escapes strings for ReportLab XML paragraph tags safely."""
    if val is None:
        return ""
    return html.escape(str(val))


# ───────────────────────────────────────────────────────────
# Two-Pass Numbered Canvas for "Page X of Y" + Running Header
# ───────────────────────────────────────────────────────────
class NumberedCanvas(canvas.Canvas):
    """Adds running headers and footers with accurate total page counts."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))

        # Running Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(54, 750, "SENTINELAPI SECURITY ASSESSMENT REPORT")
            self.drawRightString(558, 750, "CONFIDENTIAL & PROPRIETARY")
            self.setStrokeColor(colors.HexColor("#e2e8f0"))
            self.setLineWidth(0.5)
            self.line(54, 742, 558, 742)

        # Running Footer (all pages)
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.5)
        self.line(54, 45, 558, 45)

        self.drawString(54, 32, "Generated by SentinelAPI Core Security Engine • Automated CI/CD Report")
        self.drawRightString(558, 32, f"Page {self._pageNumber} of {page_count}")
        self.restoreState()


