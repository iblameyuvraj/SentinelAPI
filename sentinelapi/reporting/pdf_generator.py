    story.append(Paragraph("1. Target Environment & Execution Telemetry", styles["h1"]))

    planned = master_result.total_planned_probes
    succeeded = master_result.total_successful_probes
    failed = master_result.total_failed_probes
    health_pct = f"{(succeeded / planned * 100):.1f}%" if planned > 0 else "100.0%"

